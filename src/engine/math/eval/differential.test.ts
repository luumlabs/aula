describe('DifferentialTests', () => {
  it('same values as the JavaScript engine', () => {
    expect(GOLDEN.length).toBeGreaterThanOrEqual(100)
    for (const [input, env, expected] of GOLDEN) {
      const e = MathParser.parse(input)
      const v = tryEvaluateDouble(e, env)
      expect(v, `«${input}» no se pudo evaluar`).not.toBeNull()
      if (v === null) continue
      expect(Math.abs(v - expected) <= 1e-9 * Math.max(1, Math.abs(expected)), `«${input}» con ${JSON.stringify(env)}: MathKit ${v}, JS ${expected}`).toBe(true)
      const exactValue = tryEvaluate(e, Object.fromEntries(Object.entries(env).map(([k, x]) => [k, MV.real(x)])))
      if (exactValue) expect(Math.abs(MV.double(exactValue) - expected) <= 1e-9 * Math.max(1, Math.abs(expected)), `«${input}» exacto: ${MV.describe(exactValue)}`).toBe(true)
    }
  })
})
